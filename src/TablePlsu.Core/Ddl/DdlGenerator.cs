using System.Text;
using TablePlsu.Core.Metadata;
using TablePlsu.Core.Sql;

namespace TablePlsu.Core.Ddl;

/// <summary>
/// Generates DDL text from metadata (Structure "DDL" popover, Copy Script As) and from the new-table editor model.
/// Output uses "\n" line endings and 4-space indentation. Identifiers are quoted only when needed.
/// </summary>
public static class DdlGenerator
{
    private const string Indent = "    ";

    /// <summary>
    /// CREATE TABLE for an existing table: columns (type, identity/generated, default, NOT NULL), constraints, then table and
    /// column comments, then the indexes that do not back a constraint. With <paramref name="extras"/> the constraint list
    /// is taken verbatim from <c>pg_get_constraintdef</c> (unique, check and exclusion constraints included); without it,
    /// the primary key and foreign keys come from the metadata and unique indexes are emitted as CREATE UNIQUE INDEX.
    /// </summary>
    public static string CreateTable(TableInfo table, TableDdlExtras? extras = null)
    {
        var qualified = SqlIdent.Qualified(table.Schema, table.Name);
        var lines = table.Columns.OrderBy(c => c.Ordinal).Select(ColumnLine).ToList();

        var backing = new HashSet<string>(StringComparer.Ordinal);
        if (extras is not null && extras.Constraints.Count > 0)
        {
            foreach (var c in extras.Constraints.OrderBy(c => ConstraintOrder(c.Type)).ThenBy(c => c.Name, StringComparer.Ordinal))
            {
                lines.Add($"CONSTRAINT {SqlIdent.QuoteIfNeeded(c.Name)} {c.Definition}");
                if (c.Type is 'p' or 'u' or 'x') backing.Add(c.Name);
            }
        }
        else
        {
            if (table.HasPrimaryKey)
            {
                var pk = $"PRIMARY KEY ({ColumnList(table.PrimaryKey)})";
                lines.Add(table.PrimaryKeyName is { Length: > 0 } n ? $"CONSTRAINT {SqlIdent.QuoteIfNeeded(n)} {pk}" : pk);
                if (table.PrimaryKeyName is not null) backing.Add(table.PrimaryKeyName);
            }
            foreach (var fk in table.ForeignKeys)
                lines.Add($"CONSTRAINT {SqlIdent.QuoteIfNeeded(fk.Name)} {ForeignKeyClause(fk)}");
        }

        var sb = new StringBuilder();
        sb.Append("CREATE TABLE ").Append(qualified).Append(" (\n");
        for (var i = 0; i < lines.Count; i++)
            sb.Append(Indent).Append(lines[i]).Append(i < lines.Count - 1 ? ",\n" : "\n");
        sb.Append(");\n");

        var comments = new List<string>();
        if (!string.IsNullOrEmpty(table.Comment))
            comments.Add($"COMMENT ON TABLE {qualified} IS {SqlIdent.Literal(table.Comment)};");
        foreach (var c in table.Columns.OrderBy(c => c.Ordinal))
        {
            if (!string.IsNullOrEmpty(c.Comment))
                comments.Add($"COMMENT ON COLUMN {qualified}.{SqlIdent.QuoteIfNeeded(c.Name)} IS {SqlIdent.Literal(c.Comment)};");
        }
        if (comments.Count > 0) sb.Append('\n').Append(string.Join("\n", comments)).Append('\n');

        var indexes = table.Indexes.Where(i => !i.IsPrimary && !backing.Contains(i.Name) && i.Definition.Length > 0).ToList();
        if (indexes.Count > 0)
        {
            sb.Append('\n');
            foreach (var i in indexes) sb.Append(i.Definition.TrimEnd(';', ' ', '\n')).Append(";\n");
        }

        if (extras is not null)
        {
            var idxComments = table.Indexes
                .Where(i => extras.IndexComments.ContainsKey(i.Name))
                .Select(i => $"COMMENT ON INDEX {SqlIdent.Qualified(table.Schema, i.Name)} IS {SqlIdent.Literal(extras.IndexComments[i.Name])};")
                .ToList();
            if (idxComments.Count > 0) sb.Append('\n').Append(string.Join("\n", idxComments)).Append('\n');
        }
        return sb.ToString();
    }

    /// <summary>One column definition line (without the trailing comma).</summary>
    public static string ColumnLine(ColumnInfo c)
    {
        var sb = new StringBuilder(SqlIdent.QuoteIfNeeded(c.Name)).Append(' ').Append(c.DataType);
        if (c.Identity == "a") sb.Append(" GENERATED ALWAYS AS IDENTITY");
        else if (c.Identity == "d") sb.Append(" GENERATED BY DEFAULT AS IDENTITY");
        else if (c.IsGenerated && !string.IsNullOrEmpty(c.Default)) sb.Append(" GENERATED ALWAYS AS (").Append(c.Default).Append(") STORED");
        else if (!string.IsNullOrEmpty(c.Default)) sb.Append(" DEFAULT ").Append(c.Default);
        if (!c.IsNullable) sb.Append(" NOT NULL");
        return sb.ToString();
    }

    /// <summary>"FOREIGN KEY (…) REFERENCES …" from <see cref="ForeignKeyInfo.Definition"/>, or built from its parts.</summary>
    public static string ForeignKeyClause(ForeignKeyInfo fk)
    {
        if (!string.IsNullOrWhiteSpace(fk.Definition)) return fk.Definition;
        var sb = new StringBuilder("FOREIGN KEY (").Append(ColumnList(fk.Columns)).Append(") REFERENCES ")
            .Append(SqlIdent.Qualified(fk.RefSchema, fk.RefTable)).Append('(').Append(ColumnList(fk.RefColumns)).Append(')');
        if (fk.OnUpdate is { Length: > 0 } u && u != "NO ACTION") sb.Append(" ON UPDATE ").Append(u);
        if (fk.OnDelete is { Length: > 0 } d && d != "NO ACTION") sb.Append(" ON DELETE ").Append(d);
        return sb.ToString();
    }

    /// <summary>"schema.table(col, …)" for the structure grid's foreign_key column.</summary>
    public static string ForeignKeyTarget(ForeignKeyInfo fk) =>
        $"{SqlIdent.Qualified(fk.RefSchema, fk.RefTable)}({ColumnList(fk.RefColumns)})";

    /// <summary>CREATE OR REPLACE VIEW / CREATE MATERIALIZED VIEW around a <c>pg_get_viewdef</c> body.</summary>
    public static string ViewDdl(string schema, string name, string definition, bool materialized)
    {
        var body = definition.Trim().TrimEnd(';').TrimEnd();
        var head = materialized ? "CREATE MATERIALIZED VIEW " : "CREATE OR REPLACE VIEW ";
        return head + SqlIdent.Qualified(schema, name) + " AS\n" + body + ";\n";
    }

    public static string RefreshMaterializedView(string schema, string name) =>
        "REFRESH MATERIALIZED VIEW " + SqlIdent.Qualified(schema, name);

    /// <summary><c>pg_get_functiondef</c> text, terminated with a semicolon.</summary>
    public static string FunctionDdl(string definition) => definition.TrimEnd().TrimEnd(';').TrimEnd() + ";\n";

    /// <summary>
    /// Statements for the new-table editor: CREATE SEQUENCE for "nextval(...)" defaults, CREATE TABLE (with the PRIMARY KEY
    /// of the ticked columns, in column order), ALTER SEQUENCE … OWNED BY, then COMMENT ON COLUMN. Validate first.
    /// </summary>
    public static IReadOnlyList<string> CreateTable(NewTableModel model)
    {
        var schema = model.Schema.Trim();
        var name = model.Name.Trim();
        var qualified = SqlIdent.Qualified(schema, name);
        var before = new List<string>();
        var after = new List<string>();
        var lines = new List<string>();
        foreach (var c in model.Columns)
        {
            var col = c.Name.Trim();
            var sb = new StringBuilder(SqlIdent.QuoteIfNeeded(col)).Append(' ').Append(c.DataType.Trim());
            string? def;
            if (DefaultChoices.IsNextVal(c.Default))
            {
                var seq = SqlIdent.Qualified(schema, $"{name}_{col}_seq");
                before.Add("CREATE SEQUENCE " + seq);
                after.Add($"ALTER SEQUENCE {seq} OWNED BY {qualified}.{SqlIdent.QuoteIfNeeded(col)}");
                def = $"nextval({SqlIdent.Literal(seq)}::regclass)";
            }
            else
            {
                def = DefaultChoices.ToExpression(c.Default);
            }
            if (def is not null) sb.Append(" DEFAULT ").Append(def);
            if (!c.IsNullable) sb.Append(" NOT NULL");
            lines.Add(sb.ToString());
        }
        var pk = model.Columns.Where(c => c.IsPrimaryKey).Select(c => c.Name.Trim()).ToList();
        if (pk.Count > 0) lines.Add($"PRIMARY KEY ({ColumnList(pk)})");

        var create = new StringBuilder("CREATE TABLE ").Append(qualified).Append(" (\n");
        for (var i = 0; i < lines.Count; i++)
            create.Append(Indent).Append(lines[i]).Append(i < lines.Count - 1 ? ",\n" : "\n");
        create.Append(')');

        foreach (var c in model.Columns)
        {
            if (!string.IsNullOrWhiteSpace(c.Comment))
                after.Add($"COMMENT ON COLUMN {qualified}.{SqlIdent.QuoteIfNeeded(c.Name.Trim())} IS {SqlIdent.Literal(c.Comment)}");
        }
        return [.. before, create.ToString(), .. after];
    }

    /// <summary>Joins statements into a script: each ends with ";" and a blank line separates them.</summary>
    public static string Script(IEnumerable<string> statements) =>
        string.Join("\n\n", statements.Select(s => s.TrimEnd().TrimEnd(';') + ";")) + "\n";

    private static string ColumnList(IEnumerable<string> names) => string.Join(", ", names.Select(SqlIdent.QuoteIfNeeded));

    private static int ConstraintOrder(char type) => type switch
    {
        'p' => 0,
        'u' => 1,
        'c' => 2,
        'x' => 3,
        'f' => 4,
        _ => 5,
    };
}
