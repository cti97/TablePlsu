/// <summary>
/// Factories for the read-only structure sub-views (spec §7). The table tab hosts them as its Structure / Indexes bottom
/// tabs (<c>TableSubViewRegistry.Register("structure" | "indexes", …)</c>); the "structure" tab kind shows both standalone.
/// </summary>
public static class StructureViews
{
    public static FrameworkElement CreateStructure(IWorkspace workspace, string schema, string table) =>
        new StructurePanel(workspace, schema, table, StructurePanel.Mode.Columns);

    public static FrameworkElement CreateIndexes(IWorkspace workspace, string schema, string table) =>
        new StructurePanel(workspace, schema, table, StructurePanel.Mode.Indexes);

    /// <summary>The DDL view of a view (editable, Ctrl+S runs CREATE OR REPLACE VIEW) or a materialized view (read-only, Refresh).</summary>
    public static FrameworkElement CreateViewDdl(IWorkspace workspace, string schema, string name) =>
        new ViewDdlPanel(workspace, schema, name);

    /// <summary>The rows of the structure grid (column_name, data_type, is_nullable, default, foreign_key, comment).</summary>
    public static List<object?[]> ColumnRows(TableInfo t) =>
    [
        .. t.Columns.OrderBy(c => c.Ordinal).Select(c => new object?[]
        {
            c.Name,
            c.DataType,
            c.IsNullable ? "YES" : "NO",
            c.Identity switch
            {
                "a" => "GENERATED ALWAYS AS IDENTITY",
                "d" => "GENERATED BY DEFAULT AS IDENTITY",
                _ => c.IsGenerated && c.Default is not null ? $"GENERATED ALWAYS AS ({c.Default}) STORED" : c.Default,
            },
            t.ForeignKeyFor(c.Name) is { } fk ? DdlGenerator.ForeignKeyTarget(fk) : null,
            c.Comment,
        }),
    ];

    /// <summary>The rows of the index grid (index_name, is_unique, columns, method, predicate, comment).</summary>
    public static List<object?[]> IndexRows(TableInfo t, TableDdlExtras extras) =>
    [
        .. t.Indexes.OrderBy(i => i.IsPrimary ? 0 : 1).ThenBy(i => i.Name, StringComparer.Ordinal).Select(i => new object?[]
        {
            i.Name,
            i.IsUnique,
            string.Join(", ", i.Columns),
            i.Method,
            i.Predicate,
            extras.IndexComments.TryGetValue(i.Name, out var c) ? c : null,
        }),
    ];

    internal static readonly IReadOnlyList<ResultColumn> ColumnHeaders =
    [
        new(0, "column_name", "text", 25), new(1, "data_type", "text", 25), new(2, "is_nullable", "text", 25),
        new(3, "default", "text", 25), new(4, "foreign_key", "text", 25), new(5, "comment", "text", 25),
    ];

    internal static readonly IReadOnlyList<ResultColumn> IndexHeaders =
    [
        new(0, "index_name", "text", 25), new(1, "is_unique", "bool", 16), new(2, "columns", "text", 25),
        new(3, "method", "text", 25), new(4, "predicate", "text", 25), new(5, "comment", "text", 25),
    ];
}

/// <summary>Model of a <see cref="StructurePanel"/>; handles Ctrl+F (focus search) for its scope.</summary>
internal sealed class StructurePanelTarget(StructurePanel panel) : ICommandTarget
{
    public bool TryExecuteCommand(string commandId, CommandContext context)
    {
        if (commandId is CommandIds.TableFilterToggle or CommandIds.EditorFind)
        {
            panel.FocusSearch();
            return true;
        }
        return false;
    }
}

/// <summary>The Structure (columns) or Indexes grid of one table, with a search box; Structure also has PK tokens and DDL.</summary>
public sealed class StructurePanel : DockPanel
{
    public enum Mode { Columns, Indexes }

    private readonly IWorkspace _ws;
    private readonly Mode _mode;
    private readonly ResultGrid _grid;
    private readonly TextBox _search;
    private readonly WrapPanel _pkTokens = new() { VerticalAlignment = VerticalAlignment.Center };
    private readonly TextBlock _status = new() { VerticalAlignment = VerticalAlignment.Center, Margin = new Thickness(8, 0, 0, 0) };
    private readonly Popup _ddlPopup;
    private readonly BulkObservableCollection<object?[]> _rows = [];
    private List<object?[]> _allRows = [];
    private DbMetadata? _loadedFrom;
    private bool _loading;
    private bool _reloadQueued;

    public StructurePanel(IWorkspace workspace, string schema, string table, Mode mode)
    {
        _ws = workspace;
        Schema = schema;
        Table = table;
        _mode = mode;
        LastChildFill = true;
        SetResourceReference(BackgroundProperty, "c.app.window");
        CommandScopes.SetScope(this, CommandScope.Grid);
        DataContext = new StructurePanelTarget(this);
        _status.SetResourceReference(TextBlock.ForegroundProperty, "c.app.mutedForeground");

        // Top bar: [Primary key: tokens]  … [search] [DDL]
        var bar = new DockPanel { Margin = new Thickness(8, 6, 8, 6), LastChildFill = true };
        SetDock(bar, Dock.Top);

        _search = new TextBox { Width = 200, VerticalContentAlignment = VerticalAlignment.Center, ToolTip = "Search columns (" + ShortcutHint() + ")" };
        _search.TextChanged += (_, _) => ApplyFilter();
        _search.PreviewKeyDown += (_, e) =>
        {
            if (e.Key == Key.Escape && _search.Text.Length > 0) { _search.Clear(); e.Handled = true; }
            else if (e.Key == Key.Down) { _grid?.FocusGrid(); e.Handled = true; }
        };
        var searchHint = new TextBlock { Text = mode == Mode.Columns ? "Search columns" : "Search indexes", IsHitTestVisible = false, Margin = new Thickness(8, 0, 0, 0), VerticalAlignment = VerticalAlignment.Center };
        searchHint.SetResourceReference(TextBlock.ForegroundProperty, "c.app.mutedForeground");
        _search.TextChanged += (_, _) => searchHint.Visibility = _search.Text.Length == 0 ? Visibility.Visible : Visibility.Collapsed;
        var searchHost = new Grid { Children = { _search, searchHint } };

        var right = new StackPanel { Orientation = Orientation.Horizontal };
        DockPanel.SetDock(right, Dock.Right);
        right.Children.Add(searchHost);

        _ddlPopup = new Popup { StaysOpen = false, Placement = PlacementMode.Bottom, AllowsTransparency = true, PopupAnimation = PopupAnimation.Fade };
        if (mode == Mode.Columns)
        {
            var ddl = new Button { Content = "DDL", Margin = new Thickness(6, 0, 0, 0), Padding = new Thickness(12, 2, 12, 2), ToolTip = "Show CREATE TABLE" };
            ddl.Click += async (_, _) => await ShowDdlAsync(ddl);
            right.Children.Add(ddl);
            _ddlPopup.PlacementTarget = ddl;
            _ddlPopup.Placement = PlacementMode.Bottom;
        }
        bar.Children.Add(right);

        var left = new StackPanel { Orientation = Orientation.Horizontal, VerticalAlignment = VerticalAlignment.Center };
        if (mode == Mode.Columns)
        {
            var label = new TextBlock { Text = "Primary key", VerticalAlignment = VerticalAlignment.Center, Margin = new Thickness(0, 0, 8, 0) };
            label.SetResourceReference(TextBlock.ForegroundProperty, "c.app.mutedForeground");
            left.Children.Add(label);
            left.Children.Add(_pkTokens);
        }
        left.Children.Add(_status);
        bar.Children.Add(left);
        Children.Add(bar);

        _grid = new ResultGrid { ShowRowNumbers = false, IsReadOnly = true, Rows = _rows };
        _grid.ResultColumns = mode == Mode.Columns ? StructureViews.ColumnHeaders : StructureViews.IndexHeaders;
        var gridBorder = new Border { BorderThickness = new Thickness(0, 1, 0, 0), Child = _grid };
        gridBorder.SetResourceReference(Border.BorderBrushProperty, "c.app.border");
        Children.Add(gridBorder);

        Loaded += OnLoaded;
        Unloaded += OnUnloaded;
    }

    public string Schema { get; }
    public string Table { get; }

    /// <summary>The table shown (null until loaded or when it does not exist).</summary>
    public TableInfo? TableInfo { get; private set; }

    public TableDdlExtras Extras { get; private set; } = TableDdlExtras.Empty;

    /// <summary>Rows currently shown (after the search filter).</summary>
    public IReadOnlyList<object?[]> VisibleRows => _rows;

    public string SearchText { get => _search.Text; set => _search.Text = value; }

    /// <summary>Completes when the current load finishes (tests).</summary>
    public Task LoadTask { get; private set; } = Task.CompletedTask;

    public void FocusSearch()
    {
        _search.Focus();
        _search.SelectAll();
    }

    /// <summary>Reloads metadata-derived rows (and constraint/comment extras).</summary>
    public Task ReloadAsync() => LoadTask = LoadAsync();

    private static string ShortcutHint() => ShortcutText.Gesture(CommandIds.TableFilterToggle) is { Length: > 0 } g ? g : "Ctrl+F";

    private void OnLoaded(object sender, RoutedEventArgs e)
    {
        _ws.Metadata.Changed += OnMetadataChanged;
        _ws.StateChanged += OnStateChanged;
        if (!ReferenceEquals(_loadedFrom, _ws.Metadata.Current) || TableInfo is null) ReloadAsync();
    }

    private void OnUnloaded(object sender, RoutedEventArgs e)
    {
        _ws.Metadata.Changed -= OnMetadataChanged;
        _ws.StateChanged -= OnStateChanged;
    }

    private void OnStateChanged(object? sender, DbSessionState state) => OnUi(() =>
    {
        if (state == DbSessionState.Connected && TableInfo is null) ReloadAsync();
    });

    // Metadata events fire on a pool thread (and StateChanged may too outside the app): marshal to this element's dispatcher.
    private void OnMetadataChanged(object? sender, MetadataChangedEventArgs e) => OnUi(() =>
    {
        if (IsLoaded && !ReferenceEquals(_loadedFrom, _ws.Metadata.Current)) ReloadAsync();
    });

    private void OnUi(Action action)
    {
        if (Dispatcher.CheckAccess()) action();
        else Dispatcher.BeginInvoke(action);
    }

    private async Task LoadAsync()
    {
        if (_loading) { _reloadQueued = true; return; }
        _loading = true;
        try
        {
            do
            {
                _reloadQueued = false;
                _status.Text = "Loading…";
                var snapshot = _ws.Metadata.Current;
                var t = await StructureServices.FindTableAsync(_ws, Schema, Table);
                Extras = t is null ? TableDdlExtras.Empty : await StructureServices.LoadExtrasAsync(_ws, Schema, Table);
                _loadedFrom = t is null ? snapshot : _ws.Metadata.Current;
                TableInfo = t;
                Show(t);
            }
            while (_reloadQueued);
        }
        finally
        {
            _loading = false;
        }
    }

    private void Show(TableInfo? t)
    {
        if (t is null)
        {
            _allRows = [];
            _status.Text = _ws.State == DbSessionState.Connected ? $"{Schema}.{Table} not found." : "Not connected.";
        }
        else
        {
            _allRows = _mode == Mode.Columns ? StructureViews.ColumnRows(t) : StructureViews.IndexRows(t, Extras);
            _status.Text = "";
        }
        _pkTokens.Children.Clear();
        if (_mode == Mode.Columns)
        {
            var pk = t?.PrimaryKey ?? [];
            if (pk.Count == 0 && t is not null)
            {
                var none = new TextBlock { Text = "none", VerticalAlignment = VerticalAlignment.Center };
                none.SetResourceReference(TextBlock.ForegroundProperty, "c.app.mutedForeground");
                _pkTokens.Children.Add(none);
            }
            foreach (var col in pk) _pkTokens.Children.Add(Token(col));
        }
        ApplyFilter();
    }

    internal static Border Token(string text)
    {
        var b = new Border { CornerRadius = new CornerRadius(3), Padding = new Thickness(6, 1, 6, 1), Margin = new Thickness(0, 0, 4, 0), Child = new TextBlock { Text = text } };
        b.SetResourceReference(Border.BackgroundProperty, "c.app.sidebarSelection");
        ((TextBlock)b.Child).SetResourceReference(TextBlock.ForegroundProperty, "c.app.windowForeground");
        return b;
    }

    private void ApplyFilter()
    {
        var q = _search.Text.Trim();
        IEnumerable<object?[]> rows = _allRows;
        if (q.Length > 0)
        {
            rows = rows.Where(r =>
                (r[0] as string)?.Contains(q, StringComparison.OrdinalIgnoreCase) == true
                || (r[_mode == Mode.Columns ? 1 : 2] as string)?.Contains(q, StringComparison.OrdinalIgnoreCase) == true
                || (r[5] as string)?.Contains(q, StringComparison.OrdinalIgnoreCase) == true);
        }
        _rows.ReplaceAll([.. rows]);
    }

    private async Task ShowDdlAsync(FrameworkElement anchor)
    {
        if (_loading) await LoadTask;
        if (TableInfo is null)
        {
            Dialogs.Info($"{Schema}.{Table} is not loaded yet.");
            return;
        }
        var sql = DdlGenerator.CreateTable(TableInfo, Extras);
        var viewer = SqlText.CreateViewer(sql, out _);
        var border = new Border { Width = 640, Height = 380, Child = viewer };
        border.SetResourceReference(StyleProperty, "PopoverBorder");
        _ddlPopup.Child = border;
        _ddlPopup.PlacementTarget = anchor;
        _ddlPopup.HorizontalOffset = anchor.ActualWidth - 640;
        _ddlPopup.IsOpen = true;
    }

    /// <summary>The CREATE TABLE text the DDL button shows (null until loaded).</summary>
    public string? Ddl => TableInfo is null ? null : DdlGenerator.CreateTable(TableInfo, Extras);
}
